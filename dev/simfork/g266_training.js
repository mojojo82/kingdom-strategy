/* v1093: Training Grounds. Button in the 4th slot next to the backpack opens the screen; Essence back-paid for chapters / Gauntlet floors;
   sawtooth costs; upgrades raise the global ATK / HP / DEF Bonus (heroBonusTotal, so Conquest + Arena + bots); milestones claim a bonus + chest;
   save / load keeps it; nothing else changes for a fresh account. Run: node dev/simfork/g266_training.js */
const fs = require("fs"), path = require("path"), assert = require("assert");
const ROOT = path.join(__dirname, "../..");
const { chromium } = require(process.env.PW_PATH || "/opt/npm-tools/node_modules/playwright");
const CHROME = process.env.CHROME_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome";
const FAKE = fs.readFileSync(path.join(ROOT, "dev/tests/fakefb.js"), "utf8"), GAME = fs.readFileSync(process.env.GAMEFILE || path.join(ROOT, "test/index.html"), "utf8");
const store = {}, call = require(path.join(ROOT, "dev/tests/fnrunner.js"))(store);
(async () => {
  const b = await chromium.launch({ executablePath: CHROME, args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] }), errs = [];
  const ctx = await b.newContext({ viewport: { width: 430, height: 932 } });
  await ctx.exposeFunction("__fbstore", (op, k, v) => { if (op === "set") store[k] = JSON.parse(v); else if (op === "del") delete store[k]; return JSON.stringify(store); });
  await ctx.exposeFunction("__fbcall", call);
  await ctx.route(/mojojo82\.github\.io/, (r) => r.fulfill({ status: 200, contentType: "text/html", body: GAME }));
  await ctx.route(/gstatic\.com\/firebasejs\/.*firebase-app-compat\.js/, (r) => r.fulfill({ status: 200, contentType: "application/javascript", body: FAKE }));
  await ctx.route(/gstatic\.com\/firebasejs\/.*(auth|firestore|functions)-compat\.js/, (r) => r.fulfill({ status: 200, contentType: "application/javascript", body: "" }));
  await ctx.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
  const P = await ctx.newPage(); P.on("pageerror", (e) => errs.push(e.message));
  await P.goto("https://mojojo82.github.io/kingdom-strategy/test/"); await P.waitForSelector("#ksAuth .box");
  await P.fill("#ksE", "tg@test.dev"); await P.fill("#ksP", "secret123"); await P.click("#ksUp");
  await P.waitForSelector("#ksN", { timeout: 15000 }); await P.fill("#ksN", "Tg"); await P.click("#ksGo"); await P.waitForTimeout(6000);
  const r = await P.evaluate(() => {
    const g = game, s = g.state, o = {};
    o.fresh = JSON.stringify(s.training); o.bonus0 = [heroBonusTotal("atk"), heroBonusTotal("hp"), heroBonusTotal("def")];
    o.costs = []; for (let lv = 0; lv < 22; lv++) o.costs.push(tgCost(lv));
    o.ms = [0, 1, 2, 3, 4, 5].map(tgMsLevel); o.msB = [0, 1, 2, 3, 4, 5].map(tgMsBonus);
    s.idle.chapter = 4; s.gauntlet.floor = 21; o.paid = g.trainSync(); o.paid2 = g.trainSync();   /* chapters 1-3 + floors 10, 20 */
    o.essAfter = s.training.essence;
    const keep = s.training.essence; s.training.essence = 5; o.noMoney = g.trainUpgrade("atk"); s.training.essence = keep + 100000;
    for (let i = 0; i < 20; i++) ["atk", "hp", "def"].forEach((k) => g.trainUpgrade(k));
    o.lv = [s.training.atk, s.training.hp, s.training.def];
    o.bonus1 = [heroBonusTotal("atk"), heroBonusTotal("hp"), heroBonusTotal("def"), heroBonusTotal("skill")];
    const tk = s.weaponTickets || 0, bk = s.idle.conquestBooks || 0, sp = s.speedups.general_1h || 0;
    o.claim = g.trainClaimMilestone(); o.claimAgain = g.trainClaimMilestone();
    o.chest = [(s.weaponTickets || 0) - tk, (s.idle.conquestBooks || 0) - bk, (s.speedups.general_1h || 0) - sp];
    o.bonus2 = heroBonusTotal("atk");
    o.botSees = botBonusFrom(1).atk;
    o.saved = JSON.parse(JSON.stringify(stateForOwnSave())).training;
    const sim = createGame({ mapSize: 3, seed: 1 }); sim.loadState(JSON.parse(JSON.stringify(stateForOwnSave()))); o.reloaded = JSON.stringify(sim.state.training);
    o.capOff = tgCap(s);
    return o;
  });
  /* the screen */
  await P.evaluate(() => { setScreen("conquest"); });
  await P.waitForTimeout(800);
  const ui = await P.evaluate(() => { const b = document.querySelector(".cq-left-grid .lg-train"); if (!b) return { btn: false }; b.click();
    const pop = document.getElementById("trainPop"); return { btn: true, open: pop && pop.style.display, lv: document.getElementById("tgLv_atk").textContent, tot: document.getElementById("tgTot_atk").textContent, ms: document.getElementById("tgMsT").textContent, claimShown: document.getElementById("tgClaim").style.display, cost: document.getElementById("tgCost_hp").textContent }; });
  await P.waitForTimeout(1500);
  const sw = await P.evaluate(() => { const h = document.querySelector("#trainPop .tg-hero"), c = h.querySelector(".tg-sw"), sh = h.querySelector(".tg-shrine");
    return { started: !!trainSword, err: getComputedStyle(h.querySelector(".tg-err")).display, cv: [c.width, c.height, c.clientWidth, c.clientHeight], hero: h.clientHeight, panel: document.querySelector("#trainPop .tg-panel").clientHeight, shrineW: sh.style.width }; });
  await (await P.$("#trainPop .tg-box")).screenshot({ path: path.join(__dirname, "g266_training.png") });
  const up = await P.evaluate(() => { const before = game.state.training.hp; document.querySelector('[data-tup="hp"]').click(); return [before, game.state.training.hp]; });
  const closed = await P.evaluate(() => { document.querySelector("#trainPop .tg-x").click(); return document.getElementById("trainPop").style.display; });
  console.log(JSON.stringify({ r, ui, sw, up, closed, errs }, null, 1));
  assert.strictEqual(r.fresh, JSON.stringify({ atk: 0, hp: 0, def: 0, ms: 0, essence: 0, chPaid: 0, gPaid: 0 }));
  assert.deepStrictEqual(r.costs.slice(0, 10), [10, 12, 14, 16, 18, 20, 22, 24, 26, 250], "block 1 sawtooth");
  assert.ok(r.costs[10] === 12 && r.costs[19] === 295 && r.costs[10] < r.costs[9], "resets cheap, each block a bit higher");
  assert.deepStrictEqual(r.ms, [20, 40, 70, 110, 160, 220]); assert.deepStrictEqual(r.msB, [50, 100, 150, 200, 250, 300]);
  assert.strictEqual(r.paid, (12 + 14 + 16) + (25 + 30), "chapters 1-3 + Gauntlet floors 10 and 20"); assert.strictEqual(r.paid2, 0, "paid once");
  assert.strictEqual(r.noMoney.ok, false);
  assert.deepStrictEqual(r.lv, [20, 20, 20]);
  assert.deepStrictEqual(r.bonus1.slice(0, 3).map((x, i) => x - r.bonus0[i]), [200, 200, 200], "+10% a level"); assert.strictEqual(r.bonus1[3], 0, "skill untouched");
  assert.ok(r.claim.ok && r.claim.bonus === 50 && !r.claimAgain.ok); assert.deepStrictEqual(r.chest, [20, 5, 2]); /* v1227: tickets x10 */
  assert.strictEqual(r.bonus2 - r.bonus0[0], 250);
  assert.ok(r.botSees > 150, "bots copy the player's total");
  assert.strictEqual(r.saved.ms, 1); assert.strictEqual(JSON.parse(r.reloaded).atk, 20, "save / load keeps it");
  assert.strictEqual(r.capOff, Infinity);
  assert.ok(ui.btn && ui.open === "flex" && ui.lv === "Lv 20" && ui.tot === "+250%" && ui.ms === "All lanes Lv 40" && ui.claimShown === "none");
  assert.deepStrictEqual(up, [20, 21]);
  assert.ok(sw.started && sw.err === "none" && sw.cv[2] > 300 && sw.cv[3] > 200 && Math.abs(sw.cv[1] / sw.cv[0] - sw.cv[3] / sw.cv[2]) < 0.02, "v1096: the sword canvas is drawing at the hero's real size");
  assert.ok(sw.hero > sw.panel * 0.6 && parseFloat(sw.shrineW) > 300, "top half = sword in the shrine");
  assert.strictEqual(closed, "none");
  assert.deepStrictEqual(errs, []);
  console.log("g266 OK");
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
